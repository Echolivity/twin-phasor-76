"""Writes the parameter-to-control mapping table (docs/UI_MAPPING.md) from the built device."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
P = json.loads((ROOT / "Twin Phasor 76.maxpat").read_text())["patcher"]
bx = {b["box"]["id"]: b["box"] for b in P["boxes"]}
src = {}
for l in P["lines"]:
    src.setdefault(l["patchline"]["source"][0], []).append(l["patchline"]["destination"][0])
SECT = [(6, "Phasor A"), (180, "Modulation"), (504, "Phasor B"), (760, "Output"), (942, "Character")]
UNIT = {0: "", 1: "", 2: "ms", 3: "Hz", 4: "dB", 5: "%"}
rows = []
for i in P["parameters"]:
    if i in ("parameterbanks", "inherited_shortname"):
        continue
    b = bx[i]; v = b["saved_attribute_attributes"]["valueof"]
    x = b["presentation_rect"][0]
    sect = [n for sx, n in SECT if x >= sx][-1]
    # follow the wiring to the gen~ parameter
    chain, cur, scale = [], i, ""
    for _ in range(4):
        nxt = [d for d in src.get(cur, []) if bx[d]["maxclass"] == "newobj"]
        if not nxt:
            break
        cur = nxt[0]; t = bx[cur]["text"]
        if t.startswith("* "):
            scale = f" × {t[2:]}"
        elif t == "!- 1":
            scale = " inverted (1 − x)"
        elif t.startswith("prepend ") and t not in ("prepend set",):
            chain.append(t.split()[1]); break
        elif t.startswith("+ 1"):
            chain.append("legacy bus name (send~)"); break
    if b["maxclass"] == "live.text":
        rng = "off / on" + (f" (labelled {v['parameter_enum'][1]})" if v["parameter_enum"][0] == v["parameter_enum"][1] else f" ({' / '.join(v['parameter_enum'])})")
        dflt = "on" if v["parameter_initial"][0] else "off"
    elif v["parameter_type"] == 2:
        rng = " / ".join(v["parameter_enum"]); dflt = v["parameter_enum"][v["parameter_initial"][0]]
    else:
        u = UNIT.get(v.get("parameter_unitstyle", 1), "")
        rng = f"{v['parameter_mmin']:g}–{v['parameter_mmax']:g} {u}".strip(); dflt = f"{v['parameter_initial'][0]:g} {u}".strip()
    rows.append((sect, v["parameter_longname"], b["maxclass"], rng, dflt, (chain[0] if chain else "—") + scale, i))
out = ["# Parameter-to-control mapping", "",
       "Generated by `tools/make_ui_mapping.py` from the built `Twin Phasor 76.maxpat`. Every control drives the gen~ parameter shown;"
       " names, ranges, defaults, option lists, object IDs and order are identical to S4 (test B14).", "",
       "| Section | Parameter (automation name) | Control | Range / options | Default | gen~ parameter | Object ID |",
       "|---|---|---|---|---|---|---|"]
for r in rows:
    out.append("| " + " | ".join(r[:5]) + f" | `{r[5]}` | `{r[6]}` |")
(ROOT / "docs" / "UI_MAPPING.md").write_text("\n".join(out) + "\n")
print(len(rows), "rows")
