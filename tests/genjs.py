if __name__ == "__main__":
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(translate(SRC.read_text()))
    print(f"wrote {OUT.relative_to(ROOT)}")
    rc1 = ROOT / "tests" / "fixtures" / "rc1_twinphasor.genexpr"   # pre-sprint DSP, for preset-compatibility tests
    (OUT.parent / "rc1_test.js").write_text(translate(rc1.read_text()))
    print("wrote tests/build/rc1_test.js")
